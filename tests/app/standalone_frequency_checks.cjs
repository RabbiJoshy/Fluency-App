const fs = require('node:fs');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const vocab = fs.readFileSync('app/js/vocab.js', 'utf8');
const modals = fs.readFileSync('app/js/flashcards-modals.js', 'utf8');
const frequency = JSON.parse(fs.readFileSync('app/data/speech-frequency/pt-literal-ground-r4-fw1-ds25-decide-expr-v1.json', 'utf8'));
const start = vocab.indexOf('function speechSourceFrequencyForSurface(');
const end = vocab.indexOf('const _cachedLemmaSourceFrequencies', start);
const hydrateStart = modals.indexOf('function hydrateTempCardFrequency(');
const hydrateEnd = modals.indexOf('function splitAwareTempCard(', hydrateStart);
const context = vm.createContext({ console, config: {languages: {portuguese: {}}}, selectedLanguage: 'portuguese', flashcards: [], currentIndex: 0 });
vm.runInContext(vocab.slice(start, end) + modals.slice(hydrateStart, hydrateEnd), context);
let renders = 0;
context.updateCard = () => { renders++; };
context.window = {applyStandaloneSourceFrequency: context.applyStandaloneSourceFrequency};
(async () => {
    const card = {targetWord: 'ser', displaySurface: 'ser'};
    context.flashcards = [card];
    context.window.loadSpeechSourceFrequency = async () => frequency;
    context.hydrateTempCardFrequency([card], {word:'ser'});
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(card.sourceFrequency, frequency.values.ser);
    assert.equal(card.sourceFrequencyUnit, 'per_million');
    assert.equal(card.sourceFrequencyBasis, 'own');
    assert.equal(card.sourceFrequencyBreakdown[0].surface, 'ser');
    assert.equal(renders, 1, 'Visible card must rerender with its loaded figure');
    const fallback = {targetWord:'unlisted-form', displaySurface:'unlisted-form'};
    context.applyStandaloneSourceFrequency(fallback, {word:'ser'}, frequency);
    assert.equal(fallback.sourceFrequency, frequency.values.ser);
    assert.equal(fallback.sourceFrequencyBasis, 'other-surface');
    assert.equal(fallback.sourceFrequencyBasisSurface, 'ser');
    let release;
    context.window.loadSpeechSourceFrequency = () => new Promise(resolve => { release = resolve; });
    context.hydrateTempCardFrequency([card], {word:'ser'});
    context.selectedLanguage = 'spanish';
    release(frequency);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(renders, 1, 'Language changes must suppress stale rerenders');
    context.selectedLanguage = 'portuguese';
    context.hydrateTempCardFrequency([card], {word:'ser'});
    context.flashcards = [{targetWord:'outro'}];
    release(frequency);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(renders, 1, 'Navigating away must suppress stale rerenders');
    assert.match(modals, /hydrateTempCardFrequency\(\[baseCard\], vocabEntry\)/);
    assert.match(modals, /hydrateTempCardFrequency\(ordered, vocabEntry\)/);
    console.log('Standalone Portuguese frequency and async navigation guards passed.');
})().catch(error => {console.error(error); process.exitCode = 1;});
